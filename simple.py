n = int(input("Введите число n")) #Ввод числа
b=0 #счёт начинается с 0
if n >=1 and n<=25: # условия для числа n
    for i in range(2, n-1): #проверка числа n на делимость 
        if n % i == 0:#обновление на 0
            b+=1#прибавляем 1
    if b>0:# условия для вывода ответа 
        print("N")# b>0 значит у числа есть делитель
    else:
        print("Y")# b не больше нуля значит оно простое
else:
     print("N не входит в диапазон")  # число не входит в диапазон
            
    
    